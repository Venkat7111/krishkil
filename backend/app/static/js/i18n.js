window.KS = window.KS || {};
KS.t = function (key) {
  const lang = localStorage.getItem('ks_lang') || 'en';
  return (KS_I18N[lang] && KS_I18N[lang][key]) || KS_I18N.en[key] || key;
};

KS.applyI18n = function () {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = KS.t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', KS.t(el.getAttribute('data-i18n-placeholder')));
  });
};
